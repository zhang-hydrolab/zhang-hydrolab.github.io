/**
 * Wires the two halves together: database -> JSON API + archive snapshot ->
 * static site -> repository root, which is what GitHub Pages serves.
 *
 *   npm run publish -- --note "Added a 2026 paper"
 */
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const API_DIR = path.join(ROOT, 'frontend', '.cache', 'api', 'v1');
const DIST = path.join(ROOT, 'frontend', 'dist');
const MANIFEST = path.join(ROOT, '.published.json');

// The site may only ever write these paths at the repository root.
const PROTECTED = ['backend', 'frontend', 'scripts', 'docs', '.github', '.git', 'node_modules', 'package.json', 'package-lock.json', 'README.md', 'CLAUDE.md', '.gitignore', '.gitattributes'];

const { values } = parseArgs({ options: { note: { type: 'string' }, 'build-only': { type: 'boolean' } } });

function run(label, args, cwd = ROOT) {
  console.log(`\n> ${label}`);
  const result = spawnSync(process.execPath, ['--disable-warning=ExperimentalWarning', ...args], { cwd, stdio: 'inherit' });
  if (result.status !== 0) {
    console.error(`\nPublish stopped: "${label}" failed. The live site files were not changed.`);
    process.exit(result.status ?? 1);
  }
}

function walk(dir, base = dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, base, out);
    else out.push(path.relative(base, full).replaceAll('\\', '/'));
  }
  return out;
}

const sha = (file) => crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex');

/** Copies dist over the root, removing only files a previous publish created. */
function syncToRoot() {
  const files = walk(DIST);
  for (const file of files) {
    const top = file.split('/')[0];
    if (PROTECTED.includes(top)) throw new Error(`Refusing to publish over protected path: ${file}`);
  }

  const previous = fs.existsSync(MANIFEST) ? JSON.parse(fs.readFileSync(MANIFEST, 'utf8')).files : [];
  const next = new Set(files);
  let removed = 0;
  for (const file of previous) {
    if (next.has(file)) continue;
    fs.rmSync(path.join(ROOT, file), { force: true });
    removed += 1;
  }

  let copied = 0;
  for (const file of files) {
    const from = path.join(DIST, file);
    const to = path.join(ROOT, file);
    if (fs.existsSync(to) && sha(from) === sha(to)) continue;
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
    copied += 1;
  }

  // Tidy directories emptied by removals.
  for (const dir of ['media', 'assets', 'news', 'api', 'earth']) {
    const full = path.join(ROOT, dir);
    if (!fs.existsSync(full)) continue;
    const prune = (d) => {
      for (const entry of fs.readdirSync(d, { withFileTypes: true })) if (entry.isDirectory()) prune(path.join(d, entry.name));
      if (d !== full && !fs.readdirSync(d).length) fs.rmdirSync(d);
    };
    prune(full);
  }

  fs.writeFileSync(MANIFEST, `${JSON.stringify({ note: 'Generated by scripts/publish.mjs. Lists the site files at the repository root.', files: files.sort() }, null, 2)}\n`);
  console.log(`\nPublished to the repository root: ${copied} changed, ${removed} removed, ${files.length} total.`);
}

run('Back end: export the public API', ['src/cli.mjs', 'export', '--out', API_DIR], path.join(ROOT, 'backend'));
if (!values['build-only']) {
  run('Back end: archive a release snapshot', ['src/cli.mjs', 'release:create', '--note', values.note ?? 'Site publish'], path.join(ROOT, 'backend'));
}
run('Front end: build the static site', ['build.mjs', '--api', API_DIR, '--media', path.join(ROOT, 'backend', 'archive', 'media')], path.join(ROOT, 'frontend'));
run('Front end: verify links and assets', ['test/check-site.mjs'], path.join(ROOT, 'frontend'));
if (!values['build-only']) {
  syncToRoot();
  console.log('\nNext: review with "git status", then commit and push to go live.');
}
